<script>
document.addEventListener("DOMContentLoaded", function () {

    function initInfiniteSlider(
        sliderSelector,
        trackSelector,
        cardSelector,
        prevSelector,
        nextSelector
    ) {

        const slider = document.querySelector(sliderSelector);
        const track = document.querySelector(trackSelector);
        const prevBtn = document.querySelector(prevSelector);
        const nextBtn = document.querySelector(nextSelector);

        if (!slider || !track || !prevBtn || !nextBtn) return;


        /* =========================================
           SETTINGS
        ========================================= */

        const TRANSITION_TIME = 600;

        let originalCards = Array.from(
            track.querySelectorAll(cardSelector)
        );

        let originalCount = originalCards.length;

        let visibleCount = 3;
        let currentIndex = 0;

        let cardWidth = 0;
        let gap = 0;

        let isMoving = false;


        /* =========================================
           RESPONSIVE VISIBLE COUNT
        ========================================= */

        function getVisibleCount() {

            if (window.innerWidth <= 767) {
                return 1;
            }

            if (window.innerWidth <= 1199) {
                return 2;
            }

            return 3;
        }


        /* =========================================
           REMOVE EXISTING CLONES
        ========================================= */

        function removeClones() {

            track.querySelectorAll(".infinite_clone")
                .forEach(function (clone) {
                    clone.remove();
                });

        }


        /* =========================================
           CREATE CLONES
        ========================================= */

        function createClones() {

            removeClones();

            visibleCount = getVisibleCount();

            originalCards = Array.from(
                track.querySelectorAll(
                    `${cardSelector}:not(.infinite_clone)`
                )
            );

            originalCount = originalCards.length;


            /*
             Clone last cards before original cards
            */

            for (let i = originalCount - visibleCount; i < originalCount; i++) {

                if (i < 0) continue;

                const clone = originalCards[i].cloneNode(true);

                clone.classList.add("infinite_clone");

                track.insertBefore(
                    clone,
                    track.firstChild
                );

            }


            /*
             Clone first cards after original cards
            */

            for (let i = 0; i < visibleCount; i++) {

                const clone =
                    originalCards[i % originalCount].cloneNode(true);

                clone.classList.add("infinite_clone");

                track.appendChild(clone);

            }


            /*
             Start from original first slide,
             not from cloned slide
            */

            currentIndex = visibleCount;

        }


        /* =========================================
           MEASURE CARD
        ========================================= */

        function calculateMeasurements() {

            const firstCard =
                track.querySelector(cardSelector);

            if (!firstCard) return;


            cardWidth =
                firstCard.getBoundingClientRect().width;


            const trackStyle =
                window.getComputedStyle(track);


            gap =
                parseFloat(trackStyle.columnGap) ||
                parseFloat(trackStyle.gap) ||
                0;

        }


        /* =========================================
           MOVE TRACK
        ========================================= */

        function moveTrack(animate = true) {

            const distance =
                currentIndex * (cardWidth + gap);


            if (animate) {

                track.style.transition =
                    `transform ${TRANSITION_TIME}ms cubic-bezier(.22,.61,.36,1)`;

            } else {

                track.style.transition = "none";

            }


            track.style.transform =
                `translate3d(-${distance}px, 0, 0)`;

        }


        /* =========================================
           NEXT
        ========================================= */

        function nextSlide() {

            if (isMoving) return;

            isMoving = true;

            currentIndex++;

            moveTrack(true);

        }


        /* =========================================
           PREVIOUS
        ========================================= */

        function previousSlide() {

            if (isMoving) return;

            isMoving = true;

            currentIndex--;

            moveTrack(true);

        }


        /* =========================================
           INFINITE RESET
        ========================================= */

        track.addEventListener(
            "transitionend",
            function () {

                /*
                 Reached cloned first slides
                */

                if (
                    currentIndex >=
                    originalCount + visibleCount
                ) {

                    currentIndex =
                        visibleCount;

                    moveTrack(false);

                }


                /*
                 Reached cloned last slides
                */

                if (
                    currentIndex <
                    visibleCount
                ) {

                    currentIndex =
                        originalCount + visibleCount - 1;

                    moveTrack(false);

                }


                isMoving = false;

            }
        );


        /* =========================================
           ARROWS
        ========================================= */

        nextBtn.addEventListener(
            "click",
            nextSlide
        );


        prevBtn.addEventListener(
            "click",
            previousSlide
        );


        /* =========================================
           RESIZE
        ========================================= */

        let resizeTimer;


        window.addEventListener(
            "resize",
            function () {

                clearTimeout(resizeTimer);


                resizeTimer = setTimeout(
                    function () {

                        createClones();

                        calculateMeasurements();

                        moveTrack(false);

                        isMoving = false;

                    },
                    200
                );

            }
        );


        /* =========================================
           INITIALIZE
        ========================================= */

        createClones();

        calculateMeasurements();

        moveTrack(false);

    }



    /* =========================================
       FIFTH SECTION
    ========================================= */

    initInfiniteSlider(

        ".index_fifth_section_slider",

        ".index_fifth_section_track",

        ".index_fifth_section_case",

        ".index_fifth_section_prev",

        ".index_fifth_section_next"

    );



    /* =========================================
       SIXTH SECTION
    ========================================= */

    initInfiniteSlider(

        ".index_sixth_section_slider",

        ".index_sixth_section_track",

        ".index_sixth_section_card",

        ".index_sixth_section_prev",

        ".index_sixth_section_next"

    );

});
</script>




