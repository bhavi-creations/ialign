<script>
document.addEventListener("DOMContentLoaded", function () {

    const faqItems =
        document.querySelectorAll(
            ".contact_third_section_faq"
        );


    faqItems.forEach(function (item) {

        const question =
            item.querySelector(
                ".contact_third_section_question"
            );

        const icon =
            item.querySelector(
                ".contact_third_section_plus"
            );


        question.addEventListener(
            "click",
            function () {

                const isOpen =
                    item.classList.contains("active");


                /* -----------------------------------------
                   OTHER FAQS CLOSE
                ----------------------------------------- */

                faqItems.forEach(function (faq) {

                    faq.classList.remove("active");

                    const faqIcon =
                        faq.querySelector(
                            ".contact_third_section_plus"
                        );

                    if (faqIcon) {
                        faqIcon.textContent = "+";
                    }

                });


                /* -----------------------------------------
                   CURRENT FAQ OPEN
                ----------------------------------------- */

                if (!isOpen) {

                    item.classList.add("active");

                    icon.textContent = "−";

                }

            }
        );

    });

});
</script>



